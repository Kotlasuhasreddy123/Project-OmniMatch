"""End-of-day digest + sponsor referral webhook service — NEW FEATURES.

FEATURE 5 (Sponsor Referral Routing):
  No existing ambient or trial-matching system provides a path from
  "trial matched" to "referral initiated." OmniMatch adds a one-click
  referral that logs the action and fires a configurable webhook.

FEATURE 7 (Daily Digest):
  Clinicians won't log in every day. OmniMatch sends an end-of-day
  summary at 17:00 local time via webhook (Slack/Teams/email gateway).
  Suppressed if inbox has zero unread items.
"""

from __future__ import annotations

import json
import logging
import uuid
from datetime import datetime, timezone

import aiosqlite
import httpx

from app.config import settings

logger = logging.getLogger(__name__)

CREATE_REFERRALS_TABLE = """
CREATE TABLE IF NOT EXISTS referrals (
    id              TEXT PRIMARY KEY,
    inbox_item_id   TEXT NOT NULL,
    nct_id          TEXT NOT NULL,
    session_id      TEXT NOT NULL,
    initiated_by    TEXT NOT NULL,
    initiated_at    TEXT NOT NULL,
    webhook_status  TEXT NOT NULL DEFAULT 'pending',
    patient_pseudo  TEXT NOT NULL DEFAULT 'REDACTED'
);
"""


async def ensure_referrals_table() -> None:
    """Create the referrals table if it doesn't exist."""
    async with aiosqlite.connect(settings.sqlite_db_path) as db:
        await db.execute(CREATE_REFERRALS_TABLE)
        await db.commit()


async def initiate_referral(
    inbox_item_id: str,
    nct_id: str,
    session_id: str,
    initiated_by: str,
    patient_pseudo: str,
    trial_title: str,
    met_criteria: list[str],
    webhook_url: str | None = None,
) -> dict:
    """Log a sponsor referral and optionally fire a webhook.

    The referral draft pre-populates NCT ID, matched criteria summary,
    and patient pseudonym — NO real PHI is ever included.

    Args:
        inbox_item_id: The inbox item this referral comes from.
        nct_id: ClinicalTrials.gov NCT ID.
        session_id: Visit session ID.
        initiated_by: Username of the clinical staff member.
        patient_pseudo: Pseudonymized patient identifier.
        trial_title: Human-readable trial title.
        met_criteria: List of met criterion strings.
        webhook_url: Optional outbound webhook URL (Slack/Teams/email).

    Returns:
        Dict with referral_id, status, and webhook_fired boolean.
    """
    await ensure_referrals_table()

    referral_id = str(uuid.uuid4())
    now = datetime.now(timezone.utc).isoformat()

    referral_payload = {
        "referral_id": referral_id,
        "nct_id": nct_id,
        "trial_title": trial_title,
        "patient_pseudo": patient_pseudo,
        "session_id": session_id,
        "initiated_by": initiated_by,
        "initiated_at": now,
        "met_criteria_summary": met_criteria[:5],  # top 5 for brevity
        "note": "Pre-screen referral generated by OmniMatch ambient AI system.",
    }

    webhook_fired = False
    webhook_status = "pending"

    if webhook_url:
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp = await client.post(
                    webhook_url,
                    json=referral_payload,
                    headers={"Content-Type": "application/json"},
                )
                webhook_fired = resp.status_code < 300
                webhook_status = "sent" if webhook_fired else f"failed_{resp.status_code}"
        except Exception as exc:
            logger.warning("Referral webhook failed: %s", exc)
            webhook_status = "failed_network"

    async with aiosqlite.connect(settings.sqlite_db_path) as db:
        await db.execute(
            """
            INSERT INTO referrals
                (id, inbox_item_id, nct_id, session_id, initiated_by,
                 initiated_at, webhook_status, patient_pseudo)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (referral_id, inbox_item_id, nct_id, session_id,
             initiated_by, now, webhook_status, patient_pseudo),
        )
        await db.commit()

    return {
        "referral_id": referral_id,
        "status": webhook_status,
        "webhook_fired": webhook_fired,
        "payload": referral_payload,
    }


async def send_daily_digest(
    digest_webhook_url: str,
    inbox_summary: dict,
) -> bool:
    """Send an end-of-day digest to a webhook endpoint.

    Suppressed automatically if unread_count == 0.

    Args:
        digest_webhook_url: Target webhook URL (Slack/Teams/email).
        inbox_summary: Dict with total, unread_count, and session summaries.

    Returns:
        True if the webhook was fired successfully.
    """
    if inbox_summary.get("unread_count", 0) == 0:
        logger.info("Daily digest suppressed — no unread inbox items.")
        return False

    payload = {
        "text": (
            f"📋 *OmniMatch Daily Digest* — {datetime.now(timezone.utc).strftime('%Y-%m-%d')}\n"
            f"• {inbox_summary['unread_count']} new trial match(es) in your inbox\n"
            f"• {inbox_summary.get('total', 0)} total items\n"
            f"Review at: {inbox_summary.get('inbox_url', 'http://localhost:3000/inbox')}"
        ),
        "unread_count": inbox_summary["unread_count"],
        "sessions_today": inbox_summary.get("sessions_today", 0),
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }

    try:
        async with httpx.AsyncClient(timeout=10.0) as client:
            resp = await client.post(
                digest_webhook_url,
                json=payload,
                headers={"Content-Type": "application/json"},
            )
            success = resp.status_code < 300
            if success:
                logger.info("Daily digest sent successfully.")
            else:
                logger.warning("Daily digest webhook returned %d", resp.status_code)
            return success
    except Exception as exc:
        logger.error("Daily digest failed: %s", exc)
        return False
